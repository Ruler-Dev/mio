// Export the current chat as a standalone HTML bundle or PDF.
// HTML bundle is self-contained — embeds all artifacts inline so the
// saved file opens anywhere. PDF uses the browser print pipeline to
// keep zero external dependencies.
(function () {
  const NS = (window.Mio = window.Mio || {});

  function esc(s) {
    return String(s || '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  }

  function buildHTML() {
    const msgs = window.chatMessages || [];
    const arts = window.allArtifacts || {};
    const title = (document.querySelector('.session-row.active .session-title')?.textContent || 'Mio chat').trim();
    const date = new Date().toLocaleString();
    const renderMd = window.renderMarkdown || (s => esc(s));
    const rows = msgs.map(m => {
      const role = m.role === 'user' ? 'You' : (m.role === 'assistant' ? 'Mio' : m.role);
      const cleaned = (m.content || '')
        .replace(/<tool_call>[\s\S]*?<\/tool_call>/g, '')
        .replace(/<think>[\s\S]*?<\/think>/g, '');
      const html = renderMd(cleaned.replace(/<antArtifact[\s\S]*?<\/antArtifact>/g, '[artifact below]'));
      return `<div class="m ${m.role}">
        <div class="role">${esc(role)}</div>
        <div class="body">${html}</div>
      </div>`;
    }).join('\n');

    const artifacts = Object.values(arts).map(a => {
      let content = '';
      if (a.type === 'text/html') content = `<iframe sandbox="allow-scripts" srcdoc="${esc(a.content)}" style="width:100%;height:500px;border:1px solid #ccc;border-radius:8px"></iframe>`;
      else if (a.type === 'image/svg+xml') content = a.content;
      else if (a.type === 'text/markdown') content = renderMd(a.content);
      else content = `<pre>${esc(a.content || '').slice(0, 8000)}</pre>`;
      return `<section class="art">
        <h3>${esc(a.title || 'Artifact')}</h3>
        <div class="meta">${esc(a.type)}</div>
        ${content}
      </section>`;
    }).join('\n');

    return `<!doctype html>
<html><head><meta charset="utf-8"><title>${esc(title)}</title>
<style>
  body { font-family: -apple-system, BlinkMacSystemFont, sans-serif; max-width: 800px; margin: 40px auto; padding: 0 20px; color: #222; line-height: 1.55; }
  header { border-bottom: 2px solid #3b82f6; padding-bottom: 12px; margin-bottom: 24px; }
  h1 { margin: 0 0 4px; font-size: 22px; }
  .date { color: #888; font-size: 12px; }
  .m { margin: 18px 0; padding: 12px 16px; border-radius: 10px; }
  .m.user { background: #eef5ff; }
  .m.assistant { background: #fafafa; border: 1px solid #eee; }
  .role { font-weight: 600; color: #3b82f6; font-size: 12px; text-transform: uppercase; letter-spacing: 0.5px; margin-bottom: 6px; }
  .body pre { background: #f3f3f3; padding: 10px; border-radius: 6px; overflow-x: auto; font-size: 13px; }
  .body code { background: #f3f3f3; padding: 1px 5px; border-radius: 3px; font-size: 13px; }
  .body table { border-collapse: collapse; margin: 10px 0; }
  .body td, .body th { border: 1px solid #ddd; padding: 6px 10px; }
  section.art { margin: 26px 0; padding: 16px; border: 1px solid #ccc; border-radius: 10px; }
  section.art h3 { margin: 0 0 4px; font-size: 16px; }
  section.art .meta { color: #888; font-family: ui-monospace, monospace; font-size: 11px; margin-bottom: 10px; }
  footer { margin-top: 40px; padding-top: 14px; border-top: 1px solid #ddd; color: #888; font-size: 11px; text-align: center; }
</style></head>
<body>
<header>
  <h1>${esc(title)}</h1>
  <div class="date">Exported on ${esc(date)} · ${msgs.length} messages · ${Object.keys(arts).length} artifacts</h1>
</header>
${rows}
${artifacts ? '<h2 style="margin-top:40px">Artifacts</h2>' + artifacts : ''}
<footer>Generated by Mio · Mio UI</footer>
</body></html>`;
  }

  function exportHTML() {
    const html = buildHTML();
    const blob = new Blob([html], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'mio-chat-' + Date.now() + '.html';
    a.click();
    setTimeout(() => URL.revokeObjectURL(url), 2000);
    if (window.toast) window.toast('Chat exported as HTML');
  }

  function exportPDF() {
    // Open the HTML in a new window, then trigger print. User picks
    // "Save as PDF" in the browser dialog — zero external deps.
    const html = buildHTML();
    const w = window.open('', '_blank');
    if (!w) { if (window.toast) window.toast('Popup blocked — allow popups to export PDF'); return; }
    w.document.open();
    w.document.write(html);
    w.document.close();
    w.onload = () => setTimeout(() => w.print(), 200);
  }

  NS.chatExport = { html: exportHTML, pdf: exportPDF, build: buildHTML };
})();
